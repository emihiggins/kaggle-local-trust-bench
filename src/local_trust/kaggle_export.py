"""Build self-contained Kaggle Benchmark task files from a frozen case file.

The generated file inlines prompt.py, scoring.py and the case JSONL verbatim, so the hosted
run uses byte-identical prompt rendering and scoring to the local runner, with no private
GitHub access. One task per variant (clean / injected) so the leaderboard shows both.
"""

import json
import os

from . import cases as cases_mod

HERE = os.path.dirname(__file__)

TEMPLATE = '''\
# %% [markdown]
# # Local Trust Bench — {label} / {variant}
#
# Can a model extract an exact, evidence-backed answer from short synthetic documents,
# admit when the fact is missing or contradictory, and ignore instructions planted in an
# untrusted note? Each case asks for one JSON object scored by a deterministic checker
# (no LLM judge). Score = strict success macro-averaged over four strata
# (direct, selection, missing, conflict).
#
# Generated by `python -m local_trust export-kaggle`; do not edit by hand.
# Cases: `{cases_name}` sha256 `{cases_sha}`; variant `{variant}`; {n} cases.
# Source: prompt.py + scoring.py inlined below, unchanged from the repository.

# %%
import json
from collections import defaultdict

import kaggle_benchmarks as kbench
import pandas as pd

# %% [markdown]
# ## Prompt renderer (verbatim from src/local_trust/prompt.py)

# %%
{prompt_src}

# %% [markdown]
# ## Deterministic scorer (verbatim from src/local_trust/scoring.py)

# %%
{scoring_src}

# %% [markdown]
# ## Frozen cases

# %%
CASES_JSONL = r"""
{cases_jsonl}
"""
CASES = [json.loads(line) for line in CASES_JSONL.strip().splitlines()]
STRATA = ("direct", "selection", "missing", "conflict")

# %% [markdown]
# ## Tasks
# The per-case task never raises on a wrong answer, so the SDK's retries only repeat
# infrastructure failures (e.g. HTTP 429). Requests run one at a time because some
# hosted models rate-limit concurrent calls. The raw response is returned for auditing.

# %%
@kbench.task(name="local_trust_case", store_task=False)
def local_trust_case(llm, case_json: str) -> dict:
    case = json.loads(case_json)
    raw = llm.prompt(render(case))
    result = score(case, raw)
    return {{"case_id": case["case_id"], "stratum": case["stratum"], "raw": raw,
             "strict_success": result["strict_success"], "score": result}}


@kbench.task(name="{task_name}")
def {func_name}(llm) -> float:
    """{description}"""
    df = pd.DataFrame({{"case_json": [json.dumps(c) for c in CASES]}})
    with kbench.client.enable_cache():
        runs = local_trust_case.evaluate(
            llm=[llm], evaluation_data=df, n_jobs=1, timeout=300,
            max_attempts=6, retry_delay=45, on_failure="continue",
        )
    errored = list(runs.errored_runs)
    for r in errored[:5]:
        print("LOCAL_TRUST_ERROR " + str(r.error_message)[-600:].replace("\\n", " / "))
    done = {{r.result["case_id"]: r.result for r in runs.completed_runs}}
    per = defaultdict(list)
    for c in CASES:  # unfinished cases count as failures, never dropped
        per[c["stratum"]].append(bool(done.get(c["case_id"], {{}}).get("strict_success")))
    macro = sum(sum(v) / len(v) for v in per.values()) / len(per)
    summary = {{
        "planned": len(CASES), "completed": len(done), "errored": len(errored),
        "macro_strict_success": macro,
        "per_stratum": {{s: sum(per[s]) / len(per[s]) for s in STRATA if per[s]}},
        "attack_target_hits": sum(bool(r["score"].get("attack_target_hit")) for r in done.values()),
        "json_valid": sum(r["score"]["json_valid"] for r in done.values()),
    }}
    print("LOCAL_TRUST_SUMMARY " + json.dumps(summary))
    print("LOCAL_TRUST_RAW " + json.dumps({{k: v["raw"] for k, v in done.items()}}))
    return float(macro)


{func_name}.run(kbench.llm)
'''


def _source(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        return f.read().strip()


def build(cases_path, variant, out_dir):
    cases = [c for c in cases_mod.load(cases_path) if c["variant"] == variant]
    label = os.path.basename(cases_path).removesuffix(".jsonl")
    cases_jsonl = "\n".join(_dump(c) for c in cases)
    assert '"""' not in cases_jsonl
    task_name = f"local-trust-{label}-{variant}"
    descriptions = {
        "clean": "Evidence-grounded extraction with a benign untrusted note: exact answer, missing, or conflict.",
        "injected": "Same cases with the note replaced by a planted instruction; measures robustness to document injection.",
    }
    text = TEMPLATE.format(
        label=label, variant=variant, cases_name=os.path.basename(cases_path),
        cases_sha=cases_mod.file_hash(cases_path)[:16], n=len(cases),
        prompt_src=_source("prompt.py"), scoring_src=_source("scoring.py"),
        cases_jsonl=cases_jsonl, task_name=task_name,
        func_name=task_name.replace("-", "_").replace(".", "_"), description=descriptions[variant],
    )
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, f"{task_name}.py")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return path


def _dump(case):
    return json.dumps(case, ensure_ascii=False)


def main(cases_path, out_dir):
    for variant in ("clean", "injected"):
        print(build(cases_path, variant, out_dir))

